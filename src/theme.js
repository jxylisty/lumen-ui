// 填充 HTML 中所有 [data-ic] 占位（支持传入指定根节点）
window.lumenFillIcons = function (parent) {
  var root = parent || document;
  root.querySelectorAll("[data-ic]").forEach(function (el) {
    var k = el.getAttribute("data-ic");
    if (LumenIcons[k]) el.innerHTML = LumenIcons[k];
  });
};

if (document.readyState === "loading") {
  document.addEventListener("DOMContentLoaded", function () { window.lumenFillIcons(); });
} else {
  window.lumenFillIcons();
}
