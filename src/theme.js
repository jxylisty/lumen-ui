// Lumen UI — 主题初始化与切换
// 放在 <head> 里同步执行，避免首屏闪烁（FOUC）。
// 主题选择写入 localStorage，跨页面保持。
(function () {
  "use strict";
  var KEY = "lumen-theme";
  var root = document.documentElement;

  function resolveTheme() {
    var saved = null;
    try { saved = localStorage.getItem(KEY); } catch (e) { /* 隐私模式忽略 */ }
    if (saved === "light" || saved === "dark") return saved;
    if (window.matchMedia && window.matchMedia("(prefers-color-scheme: dark)").matches) return "dark";
    return "light";
  }

  var cur = resolveTheme();
  root.setAttribute("data-theme", cur);

  // 当前主题："light" | "dark"
  window.lumenTheme = function () { return root.getAttribute("data-theme") || "light"; };

  // 设置主题：传 "light"/"dark" 固定，不传则在两态间切换。选择会被记住。
  window.lumenSetTheme = function (mode) {
    var next = (mode === "light" || mode === "dark") ? mode : (cur === "dark" ? "light" : "dark");
    try { localStorage.setItem(KEY, next); } catch (e) { /* ignore */ }
    root.setAttribute("data-theme", next);
    cur = next;
    document.dispatchEvent(new CustomEvent("lumen:themechange", { detail: { theme: next } }));
  };

  window.lumenToggleTheme = function () { window.lumenSetTheme(); };

  // 读取 CSS 变量值（图表等动态生成元素取色用）
  window.lumenVar = function (name) {
    return getComputedStyle(root).getPropertyValue(name).trim();
  };
})();

